"""
Page builder for everything beyond the Home page.

The site has no build step and none is being introduced: this script is a
tool, not a dependency. It writes plain .html files that stand on their own,
and it exists for one reason — the Work with Experts, Share Your Feedback and
footer sections have to be *the same* on every page. Rather than paste them
into twenty files and watch them drift, the script lifts them out of
hero-full.html at build time, so Home stays the single source for them.

Run it from the site directory after changing Home or the page data below:

    python3 build-pages.py

Content here is placeholder, pending the SEO team's copy.
"""

