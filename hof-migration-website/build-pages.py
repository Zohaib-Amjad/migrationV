# --------------------------------------------------------------------------


def block(source, start, end):
    """Return source[start .. end] inclusive, by literal markers."""
    i = source.index(start)
    j = source.index(end, i) + len(end)
    return source[i:j]


def load_partials():
    src = HOME.read_text(encoding='utf-8')
    nav = block(src, '<header class="nav">', '</header>')
    # the nav sits eight spaces deep inside the hero; the shell below puts it
    # at six, so pull the whole block left by two
    nav = '\n'.join(line[2:] if line.startswith('  ') else line for line in nav.split('\n'))
    return {
        'nav': nav,
        'expert_cta': block(src, '<section class="expert-cta" id="consultation-form">', '\n  </section>'),
        'feedback': block(src, '<section class="feedback" id="feedback">', '\n  </section>'),
        'footer': block(src, '<footer class="footer">', '\n  </footer>'),
    }


def nav_for_page(nav, has_consultation):
    """Point the Home page's in-page anchors at Home when we're not on it."""
    nav = nav.replace('<a href="/" class="nav__logo">', '<a href="hero-full.html" class="nav__logo">')
    nav = nav.replace('href="#services" class="nav__link nav__link--dropdown"',
                      'href="services.html" class="nav__link nav__link--dropdown"')
    nav = nav.replace('<a href="#reviews" class="nav__link">',
                      '<a href="hero-full.html#reviews" class="nav__link">')
    if not has_consultation:
        nav = nav.replace('<a href="#consultation" class="btn btn--panel">',
                          '<a href="hero-full.html#consultation" class="btn btn--panel">')
    return nav


def footer_for_page(footer):
    """The footer's one in-page anchor is the services section on Home."""
    return footer.replace('href="hero-full.html#services"', 'href="hero-full.html#services"')


