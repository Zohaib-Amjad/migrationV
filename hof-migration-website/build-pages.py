def brandmark_svg():
    """The lockup, inlined so its three parts can be animated separately."""
    svg = (ROOT / 'assets' / 'icons-v2' / 'logo-brand.svg').read_text(encoding='utf-8').strip()
    # drawn white here: the stage is dark in both themes
    svg = svg.replace('fill="black"', 'fill="#ffffff"')
    # The three drawn elements, in document order: mark, stem, wordmark. Split
    # rather than replace-first three times — a replacement leaves "<path "
    # intact, so the next pass would land on the same element again.
    parts = svg.split('<path ')
    if len(parts) != 4:
        sys.exit(f'logo-brand.svg: expected 3 paths, found {len(parts) - 1}')
    svg = parts[0] + ''.join(
        f'<path class="{cls}" ' + part
        for cls, part in zip(('bm-mark', 'bm-stem', 'bm-word'), parts[1:]))
    svg = svg.replace('<svg ', '<svg aria-hidden="true" ', 1)
    return '\n'.join('          ' + line for line in svg.split('\n'))


